/**
 * Projects the canonical country and currency records from utils into a
 * committed, UI-private module. This keeps the public UI package browser-safe
 * without creating a runtime dependency on the internal utils package.
 *
 * `--emit` refreshes the artifact; the default mode fails on drift.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const outputPath = join(root, "packages/ui/src/data/geography.generated.ts")
const emit = process.argv.includes("--emit")

const countries = await readLiteralExport("packages/utils/src/countries.ts", "countries")
const currencies = Object.assign(
  {},
  await readLiteralExport("packages/utils/src/currencies/part-1.ts", "currenciesPart1"),
  await readLiteralExport("packages/utils/src/currencies/part-2.ts", "currenciesPart2"),
  await readLiteralExport("packages/utils/src/currencies/part-3.ts", "currenciesPart3"),
)

const uiCountries = countries.flat().map(({ code, name }) => ({ name, code }))
const uiCurrencies = Object.fromEntries(
  Object.entries(currencies).map(([code, record]) => [
    code,
    { code: record.code, name: record.name, symbol: record.symbol },
  ]),
)

const output = `// Generated by scripts/generate-ui-geography-data.mjs. Do not edit by hand.\n\nexport const countries = ${JSON.stringify(uiCountries, null, 2)} as const\n\nexport const currencies = ${JSON.stringify(uiCurrencies, null, 2)} as const\n`

if (emit) {
  writeFileSync(outputPath, output)
  console.log(
    `generate-ui-geography-data: emitted ${uiCountries.length} countries and ${Object.keys(uiCurrencies).length} currencies`,
  )
} else if (readFileSync(outputPath, "utf8") !== output) {
  console.error(
    "UI geography data is stale. Run `pnpm generate:ui-geography-data` and commit the result.",
  )
  process.exit(1)
} else {
  console.log(
    `check-ui-geography-data: OK (${uiCountries.length} countries; ${Object.keys(uiCurrencies).length} currencies)`,
  )
}

async function readLiteralExport(relativePath, exportName) {
  const source = readFileSync(join(root, relativePath), "utf8")
  const declaration = `export const ${exportName} =`
  if (!source.startsWith(declaration)) {
    throw new Error(`${relativePath} must begin with ${declaration}`)
  }
  const moduleSource = source.replace(declaration, "export default")
  const dataUrl = `data:text/javascript;base64,${Buffer.from(moduleSource).toString("base64")}`
  return (await import(dataUrl)).default
}
