#!/usr/bin/env node
/**
 * Generates the typed API clients declared in `scripts/api-clients.json`.
 *
 * Two inputs, and they are not interchangeable (ADR-0023):
 *
 *   the tracked OpenAPI document  ->  the SHAPE of each operation
 *   the resolved deployment graph ->  WHICH KEY may call it
 *
 * `x-voyant-key-kind` is stamped by `buildSelectedGraphOpenApiDocuments` at
 * composition time and appears in none of the tracked documents — writing it
 * into them was tried and reverted, because they are produced without a graph
 * (see check-openapi-key-kind-authority.mjs). So the capability line is read
 * here from the graph, through the single derivation every other reader uses.
 *
 * `keyKindForPath` is imported, never reimplemented. The runtime middleware,
 * the authority checker and this generator must agree on which key may call a
 * route, and the only way to guarantee that is for there to be one answer.
 *
 * Usage: node scripts/generate-api-client.mjs [--check]
 */
import { execFile } from "node:child_process"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"

import { keyKindForPath, readApiBundles } from "./lib/openapi-key-kind.mjs"

const execFileAsync = promisify(execFile)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const GRAPH = "apps/operator/.voyant/deployment-graph.generated.json"

function requireGraph() {
  try {
    return JSON.parse(readFileSync(path.join(root, GRAPH), "utf8"))
  } catch {
    throw new Error(
      `generate:api-client: ${GRAPH} is missing; run \`pnpm --filter operator prepare:verify\` first.`,
    )
  }
}

/**
 * The publishable subset, as a union of path literals.
 *
 * Derived from the graph rather than filtered out of the document, because a
 * document says nothing about credentials. An operation the graph does not
 * classify is secret — silence is a denial, so a bundle nobody remembered to
 * declare fails closed rather than widening the browser-reachable surface.
 */
function publishablePaths(bundles, document) {
  return Object.keys(document.paths ?? {})
    .filter((route) => keyKindForPath(bundles, route) === "publishable")
    .sort()
}

function keyKindModule(paths) {
  const union =
    paths.length > 0
      ? paths.map((route) => `\n  | ${JSON.stringify(route)}`).join("")
      : "\n  | never"
  return `/**
 * GENERATED by \`pnpm generate:api-client\` — do not edit.
 *
 * Which operations each credential may call, derived from the \`publishable\` and
 * \`guardedIntake\` declarations in the resolved deployment graph.
 *
 * An operation moving between the two is a BREAKING type change here, which is
 * the correct signal: it moves the browser-reachable surface.
 */
import type { paths } from "./paths.js"

/** Paths a publishable (\`pk_\`) key may call. */
export type PublishablePath =${union}

/**
 * The surface a publishable key sees. A secret-only operation is absent from
 * this type, so calling one is a compile error rather than a runtime 403.
 */
export type PublishablePaths = Pick<paths, PublishablePath>

/** The surface a secret (\`sk_\`) key sees: every operation on the document. */
export type SecretPaths = paths
`
}

async function generate(client, bundles) {
  const documentPath = path.join(root, client.document)
  const outDir = path.join(root, client.outDir)
  mkdirSync(outDir, { recursive: true })

  const pathsFile = path.join(outDir, "paths.ts")
  await execFileAsync("npx", ["openapi-typescript", documentPath, "-o", pathsFile], {
    cwd: root,
    maxBuffer: 256 * 1024 * 1024,
  })

  if (client.keyKinds) {
    const document = JSON.parse(readFileSync(documentPath, "utf8"))
    const routes = publishablePaths(bundles, document)
    writeFileSync(path.join(outDir, "key-kind.ts"), keyKindModule(routes))
    return { routes: routes.length, total: Object.keys(document.paths ?? {}).length }
  }
  return { routes: 0, total: 0 }
}

const { clients } = JSON.parse(readFileSync(path.join(root, "scripts/api-clients.json"), "utf8"))
const bundles = readApiBundles(requireGraph())

for (const client of clients) {
  const { routes, total } = await generate(client, bundles)
  const summary = client.keyKinds ? ` (${routes}/${total} paths publishable)` : ""
  console.log(`generate:api-client: ${client.outDir}${summary}`)
}

// biome owns the formatting of everything tracked, and the generated modules are
// tracked. Formatting here rather than in a shell `&&` keeps a non-zero exit
// from the formatter failing the generator, instead of leaving unformatted
// output behind that the drift check then reports as a diff.
await execFileAsync(
  "npx",
  [
    "biome",
    "format",
    "--write",
    "--files-max-size=8388608",
    ...clients.map((client) => path.join(root, client.outDir)),
  ],
  { cwd: root, maxBuffer: 64 * 1024 * 1024 },
)
