#!/usr/bin/env node
/**
 * Generates the typed API clients declared in `scripts/api-clients.json`.
 *
 * Two inputs, and they are not interchangeable (ADR-0023):
 *
 *   the tracked OpenAPI document  ->  the SHAPE of each operation
 *   the resolved deployment graph ->  WHICH KEY may call it
 *
 * `x-voyant-key-kind` is stamped by `buildSelectedGraphOpenApiDocuments` at
 * composition time and appears in none of the tracked documents — writing it
 * into them was tried and reverted, because they are produced without a graph
 * (see check-openapi-key-kind-authority.mjs). So the capability line is read
 * here from the graph, through the single derivation every other reader uses.
 *
 * `keyKindForPath` is imported, never reimplemented. The runtime middleware,
 * the authority checker and this generator must agree on which key may call a
 * route, and the only way to guarantee that is for there to be one answer.
 *
 * Usage: node scripts/generate-api-client.mjs [--check]
 */
import { execFile } from "node:child_process"
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"

import { keyKindForPath, readApiBundles } from "./lib/openapi-key-kind.mjs"
import { trackedFilesIn } from "./lib/tracked-files.mjs"

const execFileAsync = promisify(execFile)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const GRAPH = "apps/operator/.voyant/deployment-graph.generated.json"

function requireGraph() {
  try {
    return JSON.parse(readFileSync(path.join(root, GRAPH), "utf8"))
  } catch {
    throw new Error(
      `generate:api-client: ${GRAPH} is missing; run \`pnpm --filter operator prepare:verify\` first.`,
    )
  }
}

/**
 * The publishable subset, as a union of path literals.
 *
 * Derived from the graph rather than filtered out of the document, because a
 * document says nothing about credentials. An operation the graph does not
 * classify is secret — silence is a denial, so a bundle nobody remembered to
 * declare fails closed rather than widening the browser-reachable surface.
 */
function publishablePaths(bundles, document) {
  return Object.keys(document.paths ?? {})
    .filter((route) => keyKindForPath(bundles, route) === "publishable")
    .sort()
}

function keyKindModule(paths) {
  const union =
    paths.length > 0
      ? paths.map((route) => `\n  | ${JSON.stringify(route)}`).join("")
      : "\n  | never"
  return `/**
 * GENERATED by \`pnpm generate:api-client\` — do not edit.
 *
 * Which operations each credential may call, derived from the \`publishable\` and
 * \`guardedIntake\` declarations in the resolved deployment graph.
 *
 * An operation moving between the two is a BREAKING type change here, which is
 * the correct signal: it moves the browser-reachable surface.
 */
import type { paths } from "./paths.js"

/** Paths a publishable (\`pk_\`) key may call. */
export type PublishablePath =${union}

/**
 * The surface a publishable key sees. A secret-only operation is absent from
 * this type, so calling one is a compile error rather than a runtime 403.
 */
export type PublishablePaths = Pick<paths, PublishablePath>

/** The surface a secret (\`sk_\`) key sees: every operation on the document. */
export type SecretPaths = paths
`
}

/**
 * The barrel for a single-document client.
 *
 * Generated rather than hand-written because it lives inside the generated
 * directory, and everything there must be produced by this script — otherwise
 * the prune below cannot tell a stale module from a file someone wrote on
 * purpose, and deletes the latter.
 */
function barrelModule() {
  return `/**
 * GENERATED by \`pnpm generate:api-client\` — do not edit.
 *
 * \`paths\` is the shape of every operation, from the tracked OpenAPI document.
 * \`PublishablePaths\` narrows it to what a \`pk_\` key may call, derived from the
 * resolved deployment graph — see docs/adr/0023-generated-api-clients.md.
 */

export type { PublishablePath, PublishablePaths, SecretPaths } from "./key-kind.js"
export type { components, operations, paths, webhooks } from "./paths.js"
`
}

/**
 * The documents a client is generated from: one named outright, or every
 * document on a surface.
 *
 * Read from the TRACKED listing rather than the filesystem, so a git worktree
 * parked in the repository root cannot contribute another checkout's documents
 * to this one's client — the false green that `trackedFilesIn` exists to
 * prevent.
 */
function resolveDocuments(client) {
  if (client.document) return [client.document]
  const tracked = trackedFilesIn(root) ?? []
  const pattern = new RegExp(`^packages/[^/]+/openapi/${client.surface}/[^/]+\\.json$`)
  return tracked.filter((file) => pattern.test(file)).sort()
}

/** `packages/finance/openapi/admin/finance.json` -> `finance`. */
const moduleNameOf = (document) => path.basename(document, ".json")

async function generateModule(document, outDir, client, bundles) {
  const documentPath = path.join(root, document)
  const name = client.document ? "paths" : moduleNameOf(document)

  await execFileAsync(
    "npx",
    ["openapi-typescript", documentPath, "-o", path.join(outDir, `${name}.ts`)],
    { cwd: root, maxBuffer: 256 * 1024 * 1024 },
  )

  if (!client.keyKinds) return { routes: 0, total: 0, files: [`${name}.ts`] }

  const parsed = JSON.parse(readFileSync(documentPath, "utf8"))
  const routes = publishablePaths(bundles, parsed)
  writeFileSync(path.join(outDir, "key-kind.ts"), keyKindModule(routes))
  writeFileSync(path.join(outDir, "index.ts"), barrelModule())
  return {
    routes: routes.length,
    total: Object.keys(parsed.paths ?? {}).length,
    files: [`${name}.ts`, "key-kind.ts", "index.ts"],
  }
}

async function generate(client, bundles) {
  const outDir = path.join(root, client.outDir)
  mkdirSync(outDir, { recursive: true })

  const documents = resolveDocuments(client)
  if (documents.length === 0) {
    throw new Error(
      `generate:api-client: ${client.outDir} matched no tracked documents. A client that ` +
        `silently generates nothing looks identical to one that is up to date.`,
    )
  }

  let routes = 0
  let total = 0
  const produced = new Set()
  for (const document of documents) {
    const result = await generateModule(document, outDir, client, bundles)
    for (const file of result.files) produced.add(file)
    routes += result.routes
    total += result.total
  }

  // A document that goes away must take its module with it. `verify:openapi-drift`
  // regenerates and diffs a FIXED list of files, so an orphan is invisible to it:
  // it is not regenerated, not compared, and keeps compiling against routes that
  // no longer exist.
  for (const existing of readdirSync(outDir)) {
    if (!existing.endsWith(".ts") || produced.has(existing)) continue
    rmSync(path.join(outDir, existing))
    console.log(`  removed ${client.outDir}/${existing} (its document is gone)`)
  }

  return { documents: documents.length, routes, total, produced }
}

/**
 * Every generated file must be registered for drift.
 *
 * Discovery is dynamic — the admin client is generated from whatever admin
 * documents are tracked — while `generated-specs.json` names files one by one.
 * So adding a document silently produces a module nothing regenerates or
 * compares. Failing here keeps the two in step, because the generator is the
 * only place that knows what it just wrote.
 */
function assertRegistered(clients, producedByOutDir) {
  const specs = JSON.parse(
    readFileSync(path.join(root, "scripts/checks/openapi/generated-specs.json"), "utf8"),
  )
  const registered = new Set(
    specs.generators.flatMap((generator) =>
      generator.command === "pnpm generate:api-client" ? generator.files : [],
    ),
  )

  const missing = []
  for (const client of clients) {
    for (const file of producedByOutDir.get(client.outDir) ?? []) {
      const repoPath = `${client.outDir}/${file}`
      if (!registered.has(repoPath)) missing.push(repoPath)
    }
  }

  if (missing.length > 0) {
    throw new Error(
      `generate:api-client produced ${missing.length} file(s) that scripts/checks/openapi/` +
        `generated-specs.json does not list, so verify:openapi-drift will never check them:\n` +
        missing.map((file) => `  ${file}`).join("\n"),
    )
  }
}

const { clients } = JSON.parse(readFileSync(path.join(root, "scripts/api-clients.json"), "utf8"))
const bundles = readApiBundles(requireGraph())

const producedByOutDir = new Map()
for (const client of clients) {
  const { documents, routes, total, produced } = await generate(client, bundles)
  producedByOutDir.set(client.outDir, produced)
  const summary = client.keyKinds ? `, ${routes}/${total} paths publishable` : ""
  console.log(`generate:api-client: ${client.outDir} (${documents} document(s)${summary})`)
}

assertRegistered(clients, producedByOutDir)

// biome owns the formatting of everything tracked, and the generated modules are
// tracked. Formatting here rather than in a shell `&&` keeps a non-zero exit
// from the formatter failing the generator, instead of leaving unformatted
// output behind that the drift check then reports as a diff.
await execFileAsync(
  "npx",
  [
    "biome",
    "format",
    "--write",
    "--files-max-size=8388608",
    ...clients.map((client) => path.join(root, client.outDir)),
  ],
  { cwd: root, maxBuffer: 64 * 1024 * 1024 },
)
